/**
 * Builds the three generated scripts the composition loads:
 *   bench.js  the app's sim core and renderers plus the film runtime (src/film.ts), as one IIFE
 *   poses.js  one escapement pose per film frame (src/precompute.ts run under Node)
 *   rms.js    per-frame loudness of the music bed, for the phosphor glow
 * Run from the repository root after `npm ci`:  node brag-output/composition/build/build.mjs
 * Needs ffmpeg on PATH for rms.js.
 */
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const comp = join(here, "..");
const FPS = 60; // keep in step with src/scenario.ts

await build({ entryPoints: [join(comp, "src/film.ts")], bundle: true, format: "iife", globalName: "Bench", target: "es2020", outfile: join(comp, "bench.js"), banner: { js: "/* Generated by build/build.mjs from src/film.ts and the app's src/. Do not edit. */" } });

const tmp = mkdtempSync(join(tmpdir(), "brag-build-"));
try {
  await build({ entryPoints: [join(comp, "src/precompute.ts")], bundle: true, format: "cjs", platform: "node", outfile: join(tmp, "precompute.cjs") });
  writeFileSync(join(comp, "poses.js"), execFileSync("node", [join(tmp, "precompute.cjs")], { maxBuffer: 1 << 26, stdio: ["ignore", "pipe", "inherit"] }));

  // The runtime's own numbers, so the timeline cues can be checked against the sim.
  await build({ entryPoints: [join(comp, "src/film.ts")], bundle: true, format: "cjs", platform: "node", outfile: join(tmp, "film.cjs") });
  const film = (await import(join(tmp, "film.cjs"))).default;
  console.log(JSON.stringify(film.report(), null, 1));
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

const rate = 6000, per = rate / FPS;
const pcm = execFileSync("ffmpeg", ["-v", "error", "-i", join(comp, "assets/music/vol-12-bed.mp3"), "-ac", "1", "-ar", String(rate), "-f", "f32le", "-"], { maxBuffer: 1 << 28 });
const samples = new Float32Array(pcm.buffer, pcm.byteOffset, Math.floor(pcm.byteLength / 4));
const raw = [];
for (let i = 0; i + per <= samples.length; i += per) {
  let sum = 0;
  for (let j = 0; j < per; j++) sum += samples[i + j] ** 2;
  raw.push(Math.sqrt(sum / per));
}
const ref = [...raw].sort((a, b) => a - b)[Math.floor(raw.length * 0.95)] || 1;
const smoothed = raw.map((_, i) => {
  let sum = 0, n = 0;
  for (let j = Math.max(0, i - 5); j <= Math.min(raw.length - 1, i + 5); j++) { sum += raw[j]; n++; }
  return +Math.min(1, sum / n / ref).toFixed(3);
});
writeFileSync(join(comp, "rms.js"), `/* Generated by build/build.mjs: music loudness per film frame (0..1). Do not edit. */\nwindow.__RMS = ${JSON.stringify(smoothed)};\n`);
console.log(`rms: ${smoothed.length} frames`);
