/**
 * Offline: step the app's real escapement (contact solver and all) along the film's balance
 * trajectory and write one pose per film frame. The stepper is too heavy to run per frame in
 * the browser; its output is a few numbers per frame.
 */
import { initialPose, step, type EscapementPose } from "../../../src/core/escapement/kinematics";
import { FPS, SEG_A, SEG_B, balanceAngle, movementTime, esc } from "./scenario";

const PHASES = ["lock", "unlock", "impulse", "drop"];
const CONTACTS = [null, "entry/locking", "entry/impulse", "exit/locking", "exit/impulse"];

function segment(seg: { from: number; to: number }) {
  const f0 = Math.ceil(seg.from * FPS), f1 = Math.floor(seg.to * FPS);
  // Warm up for two film seconds so the wheel has settled into its rhythm before the first frame.
  const warm = 2 * FPS;
  let t = (f0 - warm) / FPS;
  let pose: EscapementPose = initialPose(esc, balanceAngle(t));
  const rows: (number | string)[][] = [];
  let violations = 0;
  for (let f = f0 - warm + 1; f <= f1; f++) {
    const nt = f / FPS;
    pose = step(esc, pose, balanceAngle(nt), Math.max(1e-6, movementTime(nt) - movementTime(t)));
    t = nt;
    if (f >= f0) {
      const c = pose.contact ? `${pose.contact.stone}/${pose.contact.face}` : null;
      rows.push([+pose.balanceAngle.toFixed(3), +pose.forkAngle.toFixed(4), +pose.wheelAngle.toFixed(4), PHASES.indexOf(pose.phase), CONTACTS.indexOf(c)]);
    }
  }
  violations = pose.violations;
  return { f0, rows, violations };
}

const A = segment(SEG_A), B = segment(SEG_B);
const out = `/* Generated by build/build.mjs from src/precompute.ts. Do not edit. */\nwindow.__POSES = ${JSON.stringify({ phases: PHASES, contacts: CONTACTS, segments: [{ f0: A.f0, rows: A.rows }, { f0: B.f0, rows: B.rows }] })};\n`;
process.stdout.write(out);
process.stderr.write(`poses: A ${A.rows.length} frames (violations ${A.violations}), B ${B.rows.length} frames (violations ${B.violations})\n`);
