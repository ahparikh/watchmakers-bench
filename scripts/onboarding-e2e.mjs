import { chromium } from "playwright";
import { createServer } from "vite";
const root = process.cwd();
const server = await createServer({ root, server: { port: 5198, strictPort: true }, logLevel: "silent" });
await server.listen();
const browser = await chromium.launch();
const out = [];
const check = (name, ok, detail = "") => out.push(`${ok ? "ok  " : "FAIL"} ${name} ${detail}`);
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errs = []; page.on("pageerror", (e) => errs.push(String(e)));
  await page.clock.install();
  await page.goto("http://localhost:5198/");
  await page.waitForSelector("#onboarding");
  check("first-run visible on fresh load", await page.isVisible("#onboarding .first-run"));
  check("hint hidden at start", !(await page.isVisible("#bench-help .hint")));
  const box = await page.locator("#regulator").boundingBox();
  check("regulator slider has a box", !!box);
  await page.screenshot({ path: "shots/onboarding-live-desktop-900.png" });
  await page.click('[data-act="trace"]');
  check("explainer opens from first-run button", await page.$eval("#bench-help details", (d) => d.open));
  await page.click('[data-act="dismiss"]');
  check("first-run hidden after Got it", !(await page.isVisible("#onboarding .first-run")));
  await page.reload();
  await page.waitForSelector("#onboarding");
  check("first-run stays hidden after reload", !(await page.isVisible("#onboarding .first-run")));
  check("explainer still reachable after dismissal", await page.isVisible("#bench-help summary"));
  await page.clock.runFor(59_000);
  check("no hint at 59 s", !(await page.isVisible("#bench-help .hint")));
  await page.clock.runFor(2_500);
  check("hint shown after 60 s", await page.isVisible("#bench-help .hint"), (await page.textContent("#bench-help .hint"))?.trim());
  await page.screenshot({ path: "shots/onboarding-live-hint.png" });
  await page.selectOption("#puzzle-select", "out-of-beat");
  await page.clock.runFor(1_500);
  check("hint cleared on puzzle change", !(await page.isVisible("#bench-help .hint")));
  await page.clock.runFor(61_000);
  check("puzzle 2 hint after 60 s", (await page.textContent("#bench-help .hint"))?.includes("Beat adjustment"));
  check("no page errors", errs.length === 0, errs.join("; "));
  const m = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await m.goto("http://localhost:5198/");
  await m.waitForSelector("#onboarding .first-run");
  const sw = await m.evaluate(() => document.documentElement.scrollWidth);
  check("mobile: no horizontal scroll", sw <= 390, `scrollWidth ${sw}`);
  await m.screenshot({ path: "shots/onboarding-live-mobile.png" });
} finally { await browser.close(); await server.close(); }
console.log(out.join("\n"));
process.exit(out.some((l) => l.startsWith("FAIL")) ? 1 : 0);
